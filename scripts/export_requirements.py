"""Write the pinned, hash-checked requirement files the Docker images install (Phase 6, Step 33).

    uv run python scripts/export_requirements.py           # rewrite docker/requirements-*.txt
    uv run python scripts/export_requirements.py --check   # exit 1 if they are out of date

Both files come from `uv.lock` (no network): `backend` is every runtime dependency; `serving` is the
closure of only the packages the serving app needs, so the serving image carries neither MLflow nor
Pandera nor their dependencies. A test fails if the checked-in files are stale.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docker"
# What the serving app imports (checked: importing it loads neither mlflow nor pandera).
SERVING_ROOTS = (
    "numpy",
    "pandas",
    "pyarrow",  # pandas uses it when present; the serving app ran with it in every check
    "joblib",
    "scikit-learn",
    "psycopg",
    "psycopg-binary",
    "sqlalchemy",
    "alembic",
    "fastapi",
    "uvicorn",
    "starlette",
    "pydantic",
    "python-multipart",
)
HEADER = (
    "# Generated by scripts/export_requirements.py from uv.lock. Do not edit by hand.\n"
    "# Installed with: pip install --require-hashes --no-deps -r <file>\n"
)


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_graph() -> dict[str, set[str]]:
    data = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    graph: dict[str, set[str]] = {}
    for package in data["package"]:
        deps = {normalise(d["name"]) for d in package.get("dependencies", [])}
        for extra in package.get("optional-dependencies", {}).values():
            deps |= {normalise(d["name"]) for d in extra}
        graph[normalise(package["name"])] = deps
    return graph


def closure(roots: tuple[str, ...]) -> set[str]:
    graph = lock_graph()
    seen: set[str] = set()
    todo = [normalise(r) for r in roots]
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        todo.extend(graph.get(name, ()))
    return seen


def export_blocks() -> list[tuple[str, str]]:
    """(normalised name, text) for every package in the full runtime export."""
    result = subprocess.run(
        ["uv", "export", "--frozen", "--no-dev", "--no-emit-project", "--no-annotate"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    blocks: list[tuple[str, str]] = []
    for line in result.stdout.splitlines(keepends=True):
        if line.startswith("#") or not line.strip():
            continue
        if line[0] not in " \t":
            blocks.append((normalise(re.split(r"[=<>;\[ ]", line, maxsplit=1)[0]), line))
        else:
            name, text = blocks[-1]
            blocks[-1] = (name, text + line)
    return blocks


def render() -> dict[str, str]:
    blocks = export_blocks()
    wanted = closure(SERVING_ROOTS)
    full = HEADER + "".join(text for _, text in blocks)
    slim = HEADER + "".join(text for name, text in blocks if name in wanted)
    return {"requirements-backend.txt": full, "requirements-serving.txt": slim}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="only report whether they are current")
    args = parser.parse_args()
    files = render()
    stale = [
        name
        for name, text in files.items()
        if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf-8") != text
    ]
    if args.check:
        print("up to date" if not stale else f"out of date: {', '.join(stale)}")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"wrote {', '.join(files)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
